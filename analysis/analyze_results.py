import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

METHOD_LABELS = {
    "sequential_baseline": "Sequential baseline",
    "parallel_fork_join": "ForkJoin parallel",
    "spark_distributed": "Spark distributed",
}


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("results/raw_results.csv"),
        help="Raw CSV generated by benchmark.BenchmarkMain.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results"),
        help="Directory for summary CSV and plots.",
    )
    return parser.parse_args()


def load_measurements(path):
    if not path.is_file():
        raise FileNotFoundError(
            f"Could not find {path}. Run the Spark benchmark before analysing results."
        )

    data = pd.read_csv(path)
    required = {
        "matrix_size",
        "method",
        "spark_master",
        "execution_environment",
        "configured_worker_slots",
        "elapsed_ms",
        "heap_pool_peak_sum_mb_estimate",
    }
    missing = required.difference(data.columns)
    if missing:
        raise ValueError(f"The raw CSV is missing required columns: {sorted(missing)}")

    data = data.copy()
    numeric_columns = [
        "matrix_size",
        "configured_worker_slots",
        "elapsed_ms",
        "heap_pool_peak_sum_mb_estimate",
    ]
    for column in numeric_columns:
        data[column] = pd.to_numeric(data[column], errors="coerce")

    data = data.dropna(subset=numeric_columns + ["method"])
    data = data[data["elapsed_ms"] > 0]
    if data.empty:
        raise ValueError("No valid timing observations were found in the raw CSV.")
    return data


def build_summary(data):
    keys = [
        "spark_master",
        "execution_environment",
        "method",
        "matrix_size",
        "configured_worker_slots",
    ]
    grouped = data.groupby(keys, dropna=False)
    summary = grouped.agg(
        repetitions=("elapsed_ms", "count"),
        median_time_ms=("elapsed_ms", "median"),
        q1_time_ms=("elapsed_ms", lambda values: values.quantile(0.25)),
        q3_time_ms=("elapsed_ms", lambda values: values.quantile(0.75)),
        median_heap_pool_peak_sum_mb_estimate=(
            "heap_pool_peak_sum_mb_estimate", "median"
        ),
    ).reset_index()
    summary["iqr_time_ms"] = summary["q3_time_ms"] - summary["q1_time_ms"]

    sequential = summary[summary["method"] == "sequential_baseline"][
        [
            "spark_master",
            "execution_environment",
            "matrix_size",
            "configured_worker_slots",
            "median_time_ms",
        ]
    ].rename(columns={"median_time_ms": "sequential_median_ms"})
    summary = summary.merge(
        sequential,
        on=[
            "spark_master",
            "execution_environment",
            "matrix_size",
            "configured_worker_slots",
        ],
        how="left",
    )
    summary["speedup_vs_sequential"] = (
            summary["sequential_median_ms"] / summary["median_time_ms"]
    )
    summary["efficiency"] = (
            summary["speedup_vs_sequential"] / summary["configured_worker_slots"]
    )
    summary.loc[summary["method"] == "sequential_baseline", "speedup_vs_sequential"] = 1.0
    summary.loc[summary["method"] == "sequential_baseline", "efficiency"] = float("nan")
    summary["method_label"] = summary["method"].map(METHOD_LABELS).fillna(summary["method"])
    return summary.sort_values(keys).reset_index(drop=True)


def make_plots(summary, plot_dir):
    plot_dir.mkdir(parents=True, exist_ok=True)
    matrix_sizes = sorted(summary["matrix_size"].dropna().astype(int).unique())
    environments = sorted(summary["execution_environment"].dropna().astype(str).unique())

    for environment in environments:
        environment_data = summary[summary["execution_environment"] == environment]
        env_tag = "".join(ch.lower() if ch.isalnum() else "_" for ch in environment).strip("_")

        for size in matrix_sizes:
            subset = environment_data[environment_data["matrix_size"] == size].copy()
            if subset.empty:
                continue
            seq_rows = subset[subset["method"] == "sequential_baseline"]
            seq_reference = seq_rows["median_time_ms"].median() if not seq_rows.empty else None
            suffix = f"_n{size}_{env_tag}"

            fig, ax = plt.subplots(figsize=(8, 5))
            if seq_reference is not None:
                ax.axhline(
                    seq_reference,
                    linestyle="--",
                    label="Sequential baseline (median across configurations)",
                )
            for method in ("parallel_fork_join", "spark_distributed"):
                values = subset[subset["method"] == method].sort_values("configured_worker_slots")
                if not values.empty:
                    ax.plot(
                        values["configured_worker_slots"],
                        values["median_time_ms"],
                        marker="o",
                        label=METHOD_LABELS[method],
                    )
            ax.set_title(f"Execution time for {size} x {size} matrices ({environment})")
            ax.set_xlabel("Parallelism parameter p (ForkJoin threads / Spark task slots)")
            ax.set_ylabel("Median end-to-end time (ms)")
            ax.grid(True, alpha=0.3)
            ax.legend()
            fig.tight_layout()
            fig.savefig(plot_dir / f"execution_time{suffix}.png", dpi=160)
            plt.close(fig)

            for metric, ylabel, title_prefix in (
                    ("speedup_vs_sequential", "Speedup (sequential median / method median)", "Speedup"),
                    ("efficiency", "Efficiency (speedup / configured worker slots)", "Strong-scaling efficiency"),
            ):
                fig, ax = plt.subplots(figsize=(8, 5))
                for method in ("parallel_fork_join", "spark_distributed"):
                    values = subset[subset["method"] == method].sort_values("configured_worker_slots")
                    if not values.empty:
                        ax.plot(
                            values["configured_worker_slots"],
                            values[metric],
                            marker="o",
                            label=METHOD_LABELS[method],
                        )
                ax.set_title(f"{title_prefix} for {size} x {size} matrices ({environment})")
                ax.set_xlabel("Parallelism parameter p")
                ax.set_ylabel(ylabel)
                ax.grid(True, alpha=0.3)
                ax.legend()
                fig.tight_layout()
                fig.savefig(plot_dir / f"{metric}{suffix}.png", dpi=160)
                plt.close(fig)

            fig, ax = plt.subplots(figsize=(8, 5))
            for method in METHOD_LABELS:
                values = subset[subset["method"] == method].sort_values("configured_worker_slots")
                if not values.empty:
                    ax.plot(
                        values["configured_worker_slots"],
                        values["median_heap_pool_peak_sum_mb_estimate"],
                        marker="o",
                        label=METHOD_LABELS[method],
                    )
            ax.set_title(f"Driver JVM heap estimate for {size} x {size} matrices ({environment})")
            ax.set_xlabel("Parallelism parameter p")
            ax.set_ylabel("Sum of peak heap-pool usage estimate (MiB)")
            ax.grid(True, alpha=0.3)
            ax.legend()
            fig.tight_layout()
            fig.savefig(plot_dir / f"driver_heap_estimate{suffix}.png", dpi=160)
            plt.close(fig)


def main():
    args = parse_args()
    data = load_measurements(args.input)
    summary = build_summary(data)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    summary_path = args.output_dir / "summary.csv"
    summary.to_csv(summary_path, index=False)
    make_plots(summary, args.output_dir / "plots")
    print(f"Summary written to: {summary_path.resolve()}")
    print(f"Plots written to: {(args.output_dir / 'plots').resolve()}")
    print("Review the raw CSV and check that each configuration has the intended repetitions.")


if __name__ == "__main__":
    main()
